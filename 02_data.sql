-- ============================================================
-- BLOQUE 5: DIM_FECHA (365 días del año 2024)
-- Generamos el calendario completo con un procedimiento.
-- ============================================================
DROP PROCEDURE IF EXISTS sp_generar_calendario;

DELIMITER $$
CREATE PROCEDURE sp_generar_calendario()
BEGIN
    DECLARE v_fecha DATE DEFAULT '2024-01-01';
    DECLARE v_fin   DATE DEFAULT '2024-12-31';

    WHILE v_fecha <= v_fin DO
        INSERT IGNORE INTO dim_fecha (
            id_fecha, fecha, anio, mes, dia,
            nombre_dia, nombre_mes, trimestre, es_fin_semana
        ) VALUES (
            CAST(DATE_FORMAT(v_fecha, '%Y%m%d') AS UNSIGNED),
            v_fecha,
            YEAR(v_fecha),
            MONTH(v_fecha),
            DAY(v_fecha),
            -- Nombre del día en español
            ELT(DAYOFWEEK(v_fecha), 'Domingo','Lunes','Martes',
                'Miércoles','Jueves','Viernes','Sábado'),
            -- Nombre del mes en español
            ELT(MONTH(v_fecha), 'Enero','Febrero','Marzo','Abril',
                'Mayo','Junio','Julio','Agosto','Septiembre',
                'Octubre','Noviembre','Diciembre'),
            QUARTER(v_fecha),
            -- Es fin de semana si es sábado(7) o domingo(1)
            IF(DAYOFWEEK(v_fecha) IN (1, 7), 1, 0)
        );
        SET v_fecha = DATE_ADD(v_fecha, INTERVAL 1 DAY);
    END WHILE;
END$$
DELIMITER ;

CALL sp_generar_calendario();


